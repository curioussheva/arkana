// Helper to get arkana by number
export function getArkanaByNumber(number: number): ArkanaInfo {
  const normalized = ((number % 22) + 22) % 22;
  return ARKANA_CARDS[normalized];
}

// Helper to get arkana by name
export function getArkanaByName(name: string): ArkanaInfo | undefined {
  return ARKANA_CARDS.find(
    (card) => card.card.toLowerCase() === name.toLowerCase()
  );
}
